CREATE TABLE engineers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT engineer_email_normalized CHECK (email = lower(email))
);

CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    description VARCHAR(10000) NOT NULL,
    requester_email VARCHAR(254) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    assignee_id BIGINT REFERENCES engineers(id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    resolved_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ticket_status_valid CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED')),
    CONSTRAINT active_ticket_has_engineer CHECK (status = 'OPEN' OR assignee_id IS NOT NULL),
    CONSTRAINT resolved_time_consistent CHECK ((status = 'RESOLVED') = (resolved_at IS NOT NULL))
);
CREATE INDEX idx_tickets_status_created ON tickets(status, created_at DESC, id DESC);
CREATE INDEX idx_tickets_assignee_created ON tickets(assignee_id, created_at DESC, id DESC);
CREATE INDEX idx_tickets_created ON tickets(created_at DESC, id DESC);

CREATE TABLE ticket_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES tickets(id),
    author VARCHAR(100) NOT NULL,
    body VARCHAR(5000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_comments_ticket_created ON ticket_comments(ticket_id, created_at, id);
